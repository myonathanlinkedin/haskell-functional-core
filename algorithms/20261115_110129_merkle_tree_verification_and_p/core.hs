module Core (
    MerkleTree,
    buildMerkleTree,
    rootHash,
    generateProof,
    verifyProof,
    Proof
) where

import Data.List (foldl')
import Data.Maybe (fromMaybe)

-- | Simple deterministic integer hash for a string.
hashString :: String -> Int
hashString = foldl' (\h c -> (h * 31 + fromEnum c) `mod` prime) 0
  where
    prime = 1000000007

-- | Combine two child hashes into a parent hash.
hashCombine :: Int -> Int -> Int
hashCombine h1 h2 = (h1 * 31 + h2) `mod` prime
  where
    prime = 1000000007

-- | Merkle tree data structure.
data MerkleTree
    = Leaf { leafHash :: Int, leafValue :: String }
    | Node { nodeHash :: Int, left :: MerkleTree, right :: MerkleTree }
    deriving (Eq, Show)

-- | Retrieve the hash stored at the root of a tree.
rootHash :: MerkleTree -> Int
rootHash (Leaf h _)   = h
rootHash (Node h _ _) = h

-- | Pad a list of values to the next power of two by repeating the last element.
padToPowerOfTwo :: [String] -> [String]
padToPowerOfTwo xs = xs ++ replicate (nextPow - length xs) (last xs)
  where
    n = length xs
    nextPow = if n == 0 then 0 else 2 ^ (ceiling (logBase 2 (fromIntegral n :: Double)) :: Int)

-- | Build a Merkle tree from a list of leaf values.
buildMerkleTree :: [String] -> MerkleTree
buildMerkleTree [] = error "Cannot build a Merkle tree from an empty list."
buildMerkleTree vals = buildFromLeaves paddedLeaves
  where
    paddedVals   = padToPowerOfTwo vals
    paddedLeaves = map (\v -> Leaf (hashString v) v) paddedVals

    buildFromLeaves :: [MerkleTree] -> MerkleTree
    buildFromLeaves [t] = t
    buildFromLeaves ts  = buildFromLeaves (pairUp ts)

    pairUp :: [MerkleTree] -> [MerkleTree]
    pairUp [] = []
    pairUp (a:b:rest) =
        let h = hashCombine (rootHash a) (rootHash b)
        in Node h a b : pairUp rest
    pairUp [_] = error "pairUp encountered an odd number of nodes, which should not happen."

-- | Proof element: sibling hash and a flag indicating whether the sibling is on the left.
type ProofElem = (Int, Bool)   -- (siblingHash, siblingIsLeft)

-- | A Merkle proof is a list of proof elements from leaf up to the root.
type Proof = [ProofElem]

-- | Generate a Merkle proof for a given leaf value, if it exists in the tree.
generateProof :: MerkleTree -> String -> Maybe Proof
generateProof tree target = go tree
  where
    go (Leaf h v)
        | v == target = Just []
        | otherwise   = Nothing
    go (Node _ l r) =
        case go l of
            Just p  -> Just $ (rootHash r, False) : p   -- sibling is right child
            Nothing -> case go r of
                Just p  -> Just $ (rootHash l, True) : p    -- sibling is left child
                Nothing -> Nothing

-- | Verify a Merkle proof against an expected root hash.
verifyProof :: Int      -- ^ Expected root hash
            -> String   -- ^ Original leaf value
            -> Proof    -- ^ Proof generated by 'generateProof'
            -> Bool
verifyProof expectedRoot leafVal proof = computedRoot == expectedRoot
  where
    leafH = hashString leafVal
    computedRoot = foldl' combine leafH proof

    combine :: Int -> ProofElem -> Int
    combine cur (siblingHash, siblingIsLeft) =
        if siblingIsLeft
            then hashCombine siblingHash cur
            else hashCombine cur siblingHash
